    [Serializable]
    public sealed class SpatialForceEffectSettings : SpellEffectSettings
    {
        [Tooltip("Pull targets toward the center or push them away from it.")]
        [SerializeField] private SpatialForceDirection direction =
            SpatialForceDirection.TowardCenter;

        [Tooltip("The point that acts as the force center. Delivery Center is recommended for lingering areas and moving spell objects.")]
        [SerializeField] private SpatialForceCenter center =
            SpatialForceCenter.DeliveryCenter;

        [Tooltip("Movement speed generated by the force in world units per second.")]
        [SerializeField, Min(0f)] private float strength = 5f;

        [Tooltip("Maximum speed this force can produce after combining overlapping sources.")]
        [SerializeField, Min(0f)] private float maximumSpeed = 8f;

        [Tooltip("How force strength changes with distance from its center.")]
        [SerializeField] private SpatialForceFalloff falloff =
            SpatialForceFalloff.None;

        [Tooltip("Distance used for falloff. Zero automatically uses the delivery's interaction radius when available.")]
        [SerializeField, Min(0f)] private float falloffDistance;

        [Tooltip("Targets this close to the center stop moving instead of oscillating across it.")]
        [SerializeField, Min(0f)] private float stopDistance = 0.12f;

        [Tooltip("Duration for a non-area force application. Area forces remain active exactly while the target is inside.")]
        [SerializeField, Min(0.02f)] private float duration = 0.25f;

        [Tooltip("Prevent forced movement from passing through selected obstacle layers.")]
        [SerializeField] private bool respectObstacles = true;

        [Tooltip("World layers that block forced movement when Respect Obstacles is enabled.")]
        [SerializeField] private LayerMask obstacleMask;

        public SpatialForceDirection Direction => direction;
        public SpatialForceCenter Center => center;
        public float Strength => Mathf.Max(0f, strength);
        public float MaximumSpeed => Mathf.Max(0f, maximumSpeed);
        public SpatialForceFalloff Falloff => falloff;
        public float FalloffDistance => Mathf.Max(0f, falloffDistance);
        public float StopDistance => Mathf.Max(0f, stopDistance);
        public float Duration => Mathf.Max(0.02f, duration);
        public bool RespectObstacles => respectObstacles;
        public LayerMask ObstacleMask => obstacleMask;

        public SpatialForceEffectSettings() { }

        public SpatialForceEffectSettings(
            SpatialForceDirection forceDirection,
            SpatialForceCenter forceCenter,
            float forceStrength,
            float maxSpeed,
            float forceDuration,
            float stoppingDistance = 0.12f,
            SpatialForceFalloff forceFalloff = SpatialForceFalloff.None,
            float falloffRange = 0f,
            bool blockByObstacles = true,
            LayerMask blockers = default)
        {
            direction = forceDirection;
            center = forceCenter;
            strength = Mathf.Max(0f, forceStrength);
            maximumSpeed = Mathf.Max(0f, maxSpeed);
            duration = Mathf.Max(0.02f, forceDuration);
            stopDistance = Mathf.Max(0f, stoppingDistance);
            falloff = forceFalloff;
            falloffDistance = Mathf.Max(0f, falloffRange);
            respectObstacles = blockByObstacles;
            obstacleMask = blockers;
        }
    }

    public abstract class SpatialForceEffectDefinitionBase :
        EffectDefinition,
        IAreaPresenceEffectDefinition
    {
        [Tooltip("Default pull or push direction.")]
        [SerializeField] private SpatialForceDirection direction =
            SpatialForceDirection.TowardCenter;
        [Tooltip("Default force-center source.")]
        [SerializeField] private SpatialForceCenter center =
            SpatialForceCenter.DeliveryCenter;
        [Tooltip("Default forced movement speed.")]
        [SerializeField, Min(0f)] private float strength = 5f;
        [Tooltip("Default maximum combined force speed.")]
        [SerializeField, Min(0f)] private float maximumSpeed = 8f;
        [Tooltip("Default distance falloff behavior.")]
        [SerializeField] private SpatialForceFalloff falloff =
            SpatialForceFalloff.None;
        [Tooltip("Default explicit falloff range. Zero infers it from the delivery.")]
        [SerializeField, Min(0f)] private float falloffDistance;
        [Tooltip("Default center dead zone.")]
        [SerializeField, Min(0f)] private float stopDistance = 0.12f;
        [Tooltip("Default duration outside persistent areas.")]
        [SerializeField, Min(0.02f)] private float duration = 0.25f;
        [Tooltip("Default obstacle-respecting behavior.")]
        [SerializeField] private bool respectObstacles = true;
        [Tooltip("Default force obstruction layers.")]
        [SerializeField] private LayerMask obstacleMask;

        public override Type SettingsType =>
            typeof(SpatialForceEffectSettings);

        public override SpellEffectSettings CreateDefaultSettings()
        {
            return new SpatialForceEffectSettings(
                direction,
                center,
                strength,
                maximumSpeed,
                duration,
                stopDistance,
                falloff,
                falloffDistance,
                respectObstacles,
                obstacleMask);
        }

        public override bool Apply(in SpellEffectContext context)
        {
            return Apply(context, CreateDefaultSettings());
        }

        public override bool Apply(
            in SpellEffectContext context,
            SpellEffectSettings settings)
        {
            SpatialForceEffectSettings resolved = Resolve(settings);
            SpellActorMotionController2D controller =
                SpellActorMotionUtility.GetOrAddController(context.Target);
            if (controller == null || resolved.Strength <= 0f)
                return false;

            ResolveCenter(
                context,
                resolved,
                out Transform centerTransform,
                out Vector2 centerPoint,
                out float inferredRadius);
            UnityEngine.Object source = context.DeliveryRuntime != null
                ? context.DeliveryRuntime
                : this;
            controller.ApplyTimedForce(
                source,
                BuildKey(context, resolved),
                centerTransform,
                centerPoint,
                inferredRadius,
                resolved,
                context.Spell != null &&
                context.Spell.Timing.TimeMode == SpellTimeMode.Unscaled);
            return true;
        }

        public bool ApplyPresence(
            in SpellEffectContext context,
            Component source,
            SpellEffectSettings settings)
        {
            if (source == null)
                return false;

            SpatialForceEffectSettings resolved = Resolve(settings);
            SpellActorMotionController2D controller =
                SpellActorMotionUtility.GetOrAddController(context.Target);
            if (controller == null || resolved.Strength <= 0f)
                return false;

            ResolveCenter(
                context,
                resolved,
                out Transform centerTransform,
                out Vector2 centerPoint,
                out float inferredRadius);
            controller.SetPersistentForce(
                source,
                BuildPresenceKey(source, resolved),
                centerTransform,
                centerPoint,
                inferredRadius,
                resolved);
            return true;
        }

        public void RemovePresence(
            GameObject target,
            Component source,
            SpellEffectSettings settings)
        {
            SpellActorMotionController2D controller =
                SpellActorMotionUtility.FindController(target);
            if (controller == null || source == null)
                return;

            controller.RemoveForce(
                source,
                BuildPresenceKey(source, Resolve(settings)));
        }

        public override string DescribeApplicationFailure(
            in SpellEffectContext context,
            SpellEffectSettings settings)
        {
            if (context.Target == null)
                return "Spatial Force needs an actor target.";
            if (SpellActorMotionUtility.FindBody(context.Target) == null)
                return "Spatial Force needs a Rigidbody2D on the target actor.";
            return "Spatial Force has zero strength or could not resolve its center.";
        }

        public override void CollectValidationIssues(
            List<SpellValidationIssue> issues,
            SpellEffectSettings settings)
        {
            if (issues == null)
                return;
            SpatialForceEffectSettings resolved = Resolve(settings);
            if (resolved.Strength <= 0f)
            {
                issues.Add(new SpellValidationIssue(
                    SpellValidationSeverity.Warning,
                    "Spatial Force has zero Strength and will not move targets."));
            }
            if (resolved.RespectObstacles &&
                resolved.ObstacleMask.value == 0)
            {
                issues.Add(new SpellValidationIssue(
                    SpellValidationSeverity.Warning,
                    "Spatial Force respects obstacles, but its Obstacle Mask is Nothing."));
            }
        }

        private SpatialForceEffectSettings Resolve(
            SpellEffectSettings settings)
        {
            return settings as SpatialForceEffectSettings ??
                   (SpatialForceEffectSettings)CreateDefaultSettings();
        }

        private static void ResolveCenter(
            in SpellEffectContext context,
            SpatialForceEffectSettings settings,
            out Transform centerTransform,
            out Vector2 centerPoint,
            out float inferredRadius)
        {
            centerTransform = null;
            inferredRadius = 0f;
            switch (settings.Center)
            {
                case SpatialForceCenter.Caster:
                    centerTransform = context.Cast.Caster != null
                        ? context.Cast.Caster.transform
                        : null;
                    centerPoint = centerTransform != null
                        ? (Vector2)centerTransform.position
                        : context.Cast.Origin;
                    break;
                case SpatialForceCenter.AimedPoint:
                    centerPoint = context.Cast.HasTargetPoint
                        ? context.Cast.TargetPoint
                        : context.HitPoint;
                    break;
                case SpatialForceCenter.ImpactPoint:
                    centerPoint = context.HitPoint;
                    break;
                default:
                    centerTransform = context.DeliveryRuntime != null
                        ? context.DeliveryRuntime.transform
                        : null;
                    centerPoint = centerTransform != null
                        ? (Vector2)centerTransform.position
                        : context.HitPoint;
                    if (context.DeliveryRuntime is
                        ISpellDeliveryInteractionVolume volume)
                    {
                        inferredRadius = volume.InteractionRadius;
                    }
                    break;
            }
        }

        private string BuildKey(
            in SpellEffectContext context,
            SpatialForceEffectSettings settings)
        {
            return $"{GetInstanceID()}:{(int)settings.Center}:{context.Cast.RootCastId}";
        }

        private string BuildPresenceKey(
            Component source,
            SpatialForceEffectSettings settings)
        {
            return $"{GetInstanceID()}:{(int)settings.Center}:{source.GetInstanceID()}";
        }
    }

